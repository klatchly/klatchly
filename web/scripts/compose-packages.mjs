// Composition of the build: writes ext/packages.server.ts and ext/packages.client.ts (the only two files of ext/
// the core imports: server/index.ts, client/src/registry.ts) from a list of package ids. Both are generated, out
// of git; `npm run typecheck`, `npm test` and `npm run build` run this first.
//
// The list, first found wins:
//   KLATCHLY_PACKAGES       ids separated by commas or spaces ("beeper,accounts,llm,writing"), e.g. a Docker build arg;
//   KLATCHLY_PACKAGES_FILE  a JSON file holding an array of ids;
//   ext/packages.json   the default, tracked by git (the packages of the owner's instance).
// Each id needs ext/<id>/server/index.ts; its client half is listed only when ext/<id>/client/index.tsx exists.
// The order of the list is kept (the registry sorts by each package's `order` anyway).
//
// Packages from elsewhere, outside Docker (in Docker: the `extra` build context, see Dockerfile):
//   KLATCHLY_EXT_DIRS       folders separated by ':', each a package folder (it has package.ts; its name is the id) or a
//                       folder of package folders. Each package is copied (not linked: tsc and the #core/* imports
//                       must see it inside web/) to ext/<id>/ with a .klatchly-extra marker; a later run refreshes the
//                       copies it made, and refuses to overwrite a folder of the tree (no marker).
//
// node scripts/compose-packages.mjs           write the two files (only when their text changes)
// node scripts/compose-packages.mjs --check   exit 1 when the files on disk are not what the list gives
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXT = join(WEB, 'ext');
const ID = /^[a-z][a-z0-9-]{0,31}$/;
const MARK = '.klatchly-extra';

const fail = (msg) => {
  console.error(`compose-packages: ${msg}`);
  process.exit(1);
};

function copyExtra() {
  const dirs = (process.env.KLATCHLY_EXT_DIRS ?? '').split(':').filter(Boolean);
  for (const d of dirs) {
    const src = resolve(d);
    if (!existsSync(src)) fail(`KLATCHLY_EXT_DIRS: ${src} does not exist`);
    const pkgs = existsSync(join(src, 'package.ts'))
      ? [src]
      : readdirSync(src, { withFileTypes: true })
          .filter((e) => e.isDirectory() && existsSync(join(src, e.name, 'package.ts')))
          .map((e) => join(src, e.name));
    if (!pkgs.length) fail(`KLATCHLY_EXT_DIRS: no package (a folder with package.ts) in ${src}`);
    for (const p of pkgs) {
      const id = basename(p);
      if (!ID.test(id)) fail(`KLATCHLY_EXT_DIRS: ${p}: the folder name is the package id, ${ID}`);
      const dest = join(EXT, id);
      if (existsSync(dest) && !existsSync(join(dest, MARK))) fail(`KLATCHLY_EXT_DIRS: ext/${id} is already in the tree (not a copy of ours)`);
      rmSync(dest, { recursive: true, force: true });
      cpSync(p, dest, { recursive: true, filter: (f) => !/[/\\](node_modules|\.git)$/.test(f) });
      writeFileSync(join(dest, MARK), `${p}\n`);
    }
  }
}

function readList() {
  let ids;
  let from;
  if (process.env.KLATCHLY_PACKAGES?.trim()) {
    ids = process.env.KLATCHLY_PACKAGES.split(/[\s,]+/).filter(Boolean);
    from = 'KLATCHLY_PACKAGES';
  } else {
    from = process.env.KLATCHLY_PACKAGES_FILE?.trim() ? resolve(process.env.KLATCHLY_PACKAGES_FILE) : join(EXT, 'packages.json');
    try {
      ids = JSON.parse(readFileSync(from, 'utf8'));
    } catch (e) {
      fail(`cannot read the package list ${from}: ${e.message}`);
    }
  }
  if (!Array.isArray(ids) || !ids.length) fail(`${from}: a non-empty array of package ids`);
  const seen = new Set();
  for (const id of ids) {
    if (typeof id !== 'string' || !ID.test(id)) fail(`${from}: ${JSON.stringify(id)} is not a package id (${ID})`);
    if (seen.has(id)) fail(`${from}: ${id} twice`);
    seen.add(id);
    if (!existsSync(join(EXT, id, 'server', 'index.ts'))) fail(`${from}: ${id} has no ext/${id}/server/index.ts`);
  }
  return { ids, from };
}

// A package id as a JavaScript name: example → example, my-pkg → myPkg.
const ident = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function render(ids, from) {
  const source = from === 'KLATCHLY_PACKAGES' ? 'KLATCHLY_PACKAGES' : from.startsWith(`${WEB}/`) ? from.slice(WEB.length + 1) : from;
  const head = `// Generated by scripts/compose-packages.mjs from ${source}: do not edit, change the list (docs/extensions.md).\n`;
  const client = ids.filter((id) => existsSync(join(EXT, id, 'client', 'index.tsx')));
  const server =
    head +
    `import type { ServerPackage } from '#core/sdk.js';\n` +
    ids.map((id) => `import ${ident(id)} from './${id}/server/index.js';\n`).join('') +
    `\n// Composition root, server side: the packages of this build. The core imports this file only (server/index.ts);\n` +
    `// its client twin is packages.client.ts. The order here does not matter: the registry sorts by each package's\n` +
    `// declared \`order\` (display, the connectors' merge order), and \`requires\` decides the start order. The core\n` +
    `// refuses to start without a connector (any one is enough).\n` +
    `export const packages: readonly ServerPackage[] = [${ids.map(ident).join(', ')}];\n`;
  const clientText =
    head +
    `import type { ClientPackage } from '../client/src/extension';\n` +
    client.map((id) => `import ${ident(id)} from './${id}/client/index';\n`).join('') +
    `\n// Composition root, client side: the listed packages that have a client half (ext/<id>/client/index.tsx), in\n` +
    `// any order: the sidebar, the augmentations' slots and the Settings sections follow each package's declared\n` +
    `// \`order\` (package.ts). The core imports this file only (client/src/registry.ts); its server twin is\n` +
    `// packages.server.ts. The client shows only what the server says is on.\n` +
    `export const packages: readonly ClientPackage[] = [${client.map(ident).join(', ')}];\n`;
  return { 'packages.server.ts': server, 'packages.client.ts': clientText };
}

const check = process.argv.includes('--check');
if (!check) copyExtra();
const { ids, from } = readList();
const files = render(ids, from);
const stale = [];
for (const [name, text] of Object.entries(files)) {
  const path = join(EXT, name);
  const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (now === text) continue;
  if (check) stale.push(`ext/${name}`);
  else writeFileSync(path, text);
}
if (stale.length) fail(`${stale.join(', ')} not what ${from} gives: run npm run compose`);
if (!check) console.log(`compose-packages: ${ids.join(', ')} (from ${from === 'KLATCHLY_PACKAGES' ? from : from.replace(`${WEB}/`, '')})`);
