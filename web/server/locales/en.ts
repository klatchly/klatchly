export type Widen<T> = T extends string
  ? string
  : T extends (...a: infer A) => string
    ? (...a: A) => string
    : { [K in keyof T]: Widen<T[K]> };

export type Messages = Widen<typeof messages>;
export interface Locale {
  /** BCP 47 code, also the file name. */
  code: string;
  /** Name in the language itself (language picker). */
  name: string;
  messages: Messages;
}

export default { code: 'en', name: 'English', messages } satisfies Locale;
